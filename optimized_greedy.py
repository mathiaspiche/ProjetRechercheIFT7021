def defined_greedy(environment, policy, max_episodes, max_steps):
  total_wins = 0
  total_stalled = 0
  all_rewards = np.zeros(max_episodes)
  for t in range(max_episodes):
    true_rewards = 0
    state, _ = environment.reset()
    done = False
    step = 0
    while not done and step < max_steps:
      action = np.argmax(policy[state])
      state, reward, done, _, _ = environment.step(action)
      step += 1
      true_rewards += reward
      if reward == 1:
        total_wins += 1
      if step == max_steps:
        reward -= 2
        total_stalled += 1

    all_rewards[t] = true_rewards
  return total_wins, total_stalled, all_rewards
